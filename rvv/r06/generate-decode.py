#!/usr/bin/env python3
"""Generate encoding constants only; never generate expected arithmetic results.

Input: frozen riscv/riscv-opcodes extensions/rv_v, SHA256 recorded in R06.
The Scala decoder adds configuration, register-group and overlap legality.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'rvv/r06/rv_v.opcodes'
OUTPUT = ROOT / 'design/src/main/scala/rvv/zve/ZveEncodings.scala'
rows = []
for line in SOURCE.read_text().splitlines():
    tokens = line.split('#')[0].split()
    if not tokens or tokens[0].startswith('$') or tokens[0].startswith('vset'):
        continue
    name = tokens[0]
    if name.startswith(('vfwadd', 'vfwsub', 'vfwmul', 'vfwmacc', 'vfwnmacc', 'vfwmsac', 'vfwnmsac', 'vfwred')):
        continue
    if name.startswith('vfwcvt') and name not in ('vfwcvt.f.x.v', 'vfwcvt.f.xu.v'):
        continue
    if name.startswith('vfncvt') and name not in ('vfncvt.x.f.w', 'vfncvt.xu.f.w', 'vfncvt.rtz.x.f.w', 'vfncvt.rtz.xu.f.w'):
        continue
    if re.match(r'v[ls].*64', name):
        continue
    match = mask = 0
    for token in tokens[1:]:
        m = re.fullmatch(r'(\d+)(?:\.\.(\d+))?=(0x[0-9a-fA-F]+|\d+)', token)
        if not m:
            continue
        hi = int(m[1]); lo = int(m[2] or m[1]); value = int(m[3], 0)
        bits = ((1 << (hi-lo+1))-1) << lo
        mask |= bits; match |= value << lo
    root = 'memory' if (match & 0x7f) in (7, 0x27) else name.split('.')[0]
    rows.append((name, root, match, mask))
roots = sorted({r[1] for r in rows})
out = ['package flow.rvv.zve', '', 'import chisel3.util.BitPat', '',
       '// Generated by rvv/r06/generate-decode.py from the frozen opcode file.',
       'object ZveOp {']
for i, root in enumerate(roots):
    out.append(f'  val {root} = {i}')
out += [f'  val count = {len(roots)}', '}', '', 'object ZveEncodings {',
        '  val forms: Seq[(String, Int, BitPat)] = Seq(']
for i, (name, root, match, mask) in enumerate(rows):
    bits = ''.join(str((match >> b) & 1) if ((mask >> b) & 1) else '?' for b in reversed(range(32)))
    out.append(f'    ("{name}", ZveOp.{root}, BitPat("b{bits}")){"," if i < len(rows)-1 else ""}')
out += ['  )', '}', '']
OUTPUT.write_text('\n'.join(out))
print(f'{len(rows)} encoding forms, {len(roots)} operation roots -> {OUTPUT}')
