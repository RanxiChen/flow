#!/usr/bin/env python3
"""Publish the explicit Scala observation schema to documentation, M-mode C and DT.

Run with --check to reject drift without writing files. Event order is the ABI.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent

def raw_ranges(first, last):
    """Disjoint masked blocks, exactly covering a closed legal-ID interval.

    OpenSBI 1.9 has a bounded 256-entry event map (including generic rows).
    Compact binding rows retain every event without advertising illegal gaps.
    """
    while first <= last:
        size = first & -first
        while size > last-first+1:
            size >>= 1
        yield first, ((1 << 64)-1) ^ (size-1)
        first += size

def outputs():
    scala = (ROOT / 'design/src/main/scala/observe/BreezeObserve.scala').read_text()
    block = scala.split('val names: Seq[String] = Seq(', 1)[1].split(')\n  val count', 1)[0]
    names = re.findall(r'"([a-z0-9_]+)"', block)
    if not names or len(names) != len(set(names)):
        raise ValueError('empty or duplicate observation event names')
    cycles = set('''cpu_cycles active_cycles frontend_starved frontend_backpressure both_blocked queue_empty queue_low queue_high queue_full
      fe_wait_itlb fe_wait_icache fe_wait_recovery fe_wait_other recovery_cycles f2_recovery_cycles itlb_pending
      iptw_queue_cycles iptw_service_cycles iptw_mem_wait ic_refill_wait il2_slot_wait il2_set_wait il2_request_wait
      backend_fp_wait backend_lsu_wait backend_serial_wait backend_feedback_wait backend_other_wait'''.split())
    sums = {'recovery_latency', 'f2_recovery_latency', 'ic_refill_latency'}
    catalog = {'version': 1, 'legacy_raw_ids': '1..20 unchanged', 'raw_base': 4096,
      'events': [{'index': i, 'raw': 4096+i, 'name': n,
        'unit': 'cycles' if n in cycles else 'cycle_sum' if n in sums else 'count'} for i,n in enumerate(names)]}
    header = '''/* Generated by tools/generate_frontend_observe_catalog.py; M-mode only. */
#ifndef BREEZE_OBSERVE_H
#define BREEZE_OBSERVE_H
#include <stdint.h>
#include "perf.h"
#define BREEZE_OBS_VERSION 1u
#define BREEZE_OBS_RAW_BASE UINT64_C(0x1000)
#define BREEZE_OBS_RAW(index) (BREEZE_OBS_RAW_BASE + (uint64_t)(index))
#define BREEZE_OBS_FREEZE UINT64_C(1)
#define BREEZE_OBS_CLEAR UINT64_C(2)
#define BREEZE_OBS_TRACE_ENABLE UINT64_C(4)
#define BREEZE_OBS_TRACE_DEPTH 16u
#define BREEZE_OBS_TRACE_WORDS 6u
'''
    header += f'#define BREEZE_OBS_COUNT {len(names)}u\n'
    header += ''.join(f'#define BREEZE_OBS_{n.upper()} {i}u\n' for i,n in enumerate(names))
    header += '''static inline uint64_t breeze_observe_control(void) { return BREEZE_CSR_READ(0x7d0); }
static inline void breeze_observe_configure(uint64_t control) { BREEZE_CSR_WRITE(0x7d0, control); }
static inline uint64_t breeze_observe_read(unsigned index) {
    BREEZE_CSR_WRITE(0x7d1, index);
    return BREEZE_CSR_READ(0x7d2);
}
static inline uint64_t breeze_observe_trace_read(unsigned entry, unsigned word) {
    if (entry >= BREEZE_OBS_TRACE_DEPTH || word >= BREEZE_OBS_TRACE_WORDS) return 0;
    BREEZE_CSR_WRITE(0x7d3, entry * 8u + word);
    return BREEZE_CSR_READ(0x7d4);
}
static inline uint64_t breeze_observe_trace_status(void) { return BREEZE_CSR_READ(0x7d5); }
/* Caller chooses the measurement window; snapshot preserves the old control. */
static inline void breeze_observe_snapshot(uint64_t values[BREEZE_OBS_COUNT]) {
    const uint64_t control = breeze_observe_control();
    breeze_observe_configure(control | BREEZE_OBS_FREEZE);
    for (unsigned i = 0; i < BREEZE_OBS_COUNT; ++i) values[i] = breeze_observe_read(i);
    breeze_observe_configure(control);
}
#endif
'''
    dts = '''/include/ "flow-kcu105-tiny.dts"

/ {
    pmu {
        compatible = "riscv,pmu";
        /* Use overflow-capable HPM3..10 for generic cycles/instructions.
         * Fixed counter0/2 remain architectural CSRs, without sampling IRQ. */
        riscv,event-to-mhpmcounters = <0x1 0x1 0x7f8>, <0x2 0x2 0x7f8>;
        riscv,event-to-mhpmevent = __GENERIC_EVENT_MAP__;
        /* Disjoint masked ranges cover only legal selectors. Keep the table
         * below OpenSBI's 256-entry limit, including generic event rows. */
        riscv,raw-event-to-mhpmcounters =
'''
    dts = dts.replace('__GENERIC_EVENT_MAP__', '<0x1 0x0 0x%x>, <0x2 0x0 0x%x>' %
      (4096+names.index('cpu_cycles'),4096+names.index('retired_instructions')))
    ranges = list(raw_ranges(1,20)) + list(raw_ranges(4096,4096+len(names)-1))
    if len(ranges)+2 >= 256:
        raise ValueError('PMU map exceeds OpenSBI capacity')
    dts += ',\n'.join('            <0x0 0x%x 0x%x 0x%x 0x7f8>' % (value,mask>>32,mask&0xffffffff)
      for value,mask in ranges)
    dts += ';\n    };\n};\n\n&cpu0 {\n    riscv,isa = "rv64imafdc_zicntr_zicsr_zifencei_zihpm_sscofpmf";\n};\n'
    return {
      'docs/frontend-observe-events.json': json.dumps(catalog, indent=2)+'\n',
      'software/breeze-mcu/include/breeze/observe.h': header,
      'linux/buildroot-external/board/flow/dts/flow/flow-kcu105-tiny-perf.dts': dts}

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, content in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit('observation ABI output is stale: '+name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print('observation catalog, C header and perf DT are consistent')
